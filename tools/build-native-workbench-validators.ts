import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {writeFileSync,readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import schema from '../contracts/created-workbench.schema.json' with {type:'json'};
import legacy from '../contracts/workbench.schema.json' with {type:'json'};
import lock from '../contracts/public-lock.schema.json' with {type:'json'};
// Static, CSP-compatible validators. Never ship Ajv's dynamic compiler to the native page.
const ajv=new Ajv2020({strict:true,allErrors:true,code:{source:true,esm:true,lines:true}});addFormats(ajv);ajv.addSchema(lock);ajv.addSchema(schema);ajv.addSchema(legacy);
let code=standaloneCode(ajv,{created:schema.$id,legacy:legacy.$id});
const imports:string[]=[];
for(const [name,path] of [['nativeFormats','ajv-formats/dist/formats'],['nativeUcs2','ajv/dist/runtime/ucs2length']] as const){
 const exact='require('+JSON.stringify(path)+')';if(code.includes(exact)){imports.push('import '+name+' from '+JSON.stringify(path+'.js')+';');code=code.replaceAll(exact,name);}
}
code=code.replaceAll('nativeUcs2.default','(nativeUcs2.default ?? nativeUcs2)');
if(/\brequire\s*\(|\bnew\s+Function\s*\(|\beval\s*\(/.test(code))throw new Error('UNSUPPORTED_DYNAMIC_VALIDATOR_OUTPUT');
const files=['contracts/created-workbench.schema.json','contracts/workbench.schema.json','contracts/public-lock.schema.json'];
const hashes=Object.fromEntries(files.map(path=>[path,createHash('sha256').update(readFileSync(path)).digest('hex')]));
const outputs={
 'src/contracts/native-workbench-validators.mjs':'// Generated by tools/build-native-workbench-validators.ts; Ajv 8.18.0 / ajv-formats 3.0.1. Do not edit.\n'+imports.join('\n')+'\n'+code,
 'src/contracts/native-workbench-validator-inputs.json':JSON.stringify(hashes,null,2)+'\n',
};
for(const [path,bytes] of Object.entries(outputs)){
 if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==bytes)throw new Error('STALE_NATIVE_WORKBENCH_VALIDATOR:'+path);}
 else writeFileSync(path,bytes);
}
console.log((process.argv.includes('--check')?'Verified':'Generated')+' static native workbench validators for '+files.length+' unchanged contract inputs');
