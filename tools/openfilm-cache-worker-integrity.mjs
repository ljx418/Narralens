import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The integrity tool of the native cache worker.
 *
 * The worker runs bytes that this repository owns: itself, the worker-local policy,
 * the media process policy of the formal render and the offline guard of the formal
 * render, plus the PINNED upstream module that draws the picture. This tool is the
 * record of what those bytes are supposed to be.
 *
 * Two rules, and they are the point of the tool:
 *
 *  - The DEFAULT is a CHECK. The tool reads bytes and compares them; it never
 *    writes anything unless `--generate` was asked for. A build that runs this tool
 *    cannot change the record it checks itself against.
 *
 *  - The manifest never hashes ITSELF, and the pinned upstream digests are never
 *    taken from a working tree. The digests of this repository's own modules are
 *    regenerated by `--generate`; the digests of the upstream come from the
 *    canonical upstream lock, which MAIN owns, and they are copied - not
 *    recomputed - so a checkout of the upstream can never overwrite the pin.
 *
 * The tool does not import the producer, does not start a process and does not use
 * the network: it reads files and compares digests. That is what makes it safe to
 * run anywhere, including in a gate that must not touch the machine.
 */

/** The repository root: this tool lives in tools/. */
const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The manifest the worker checks itself against. It is the ONLY file this tool writes. */
const MANIFEST_PATH = "src/adapters/openfilm/cache-worker-integrity.json";

/** The canonical upstream lock. It is the authority for the digests of the upstream. */
const UPSTREAM_LOCK_PATH = "contracts/openfilm-upstream-lock.json";

/**
 * The modules of THIS repository that take part in the draw.
 *
 * The list is fixed here, in the tool: a caller cannot hand the tool another set
 * of files, and the manifest cannot name a file that the tool does not know.
 */
const HOST_MODULES = Object.freeze([
  "src/adapters/openfilm/openfilm-cache-worker.mjs",
  "src/adapters/openfilm/cache-worker-policy.mjs",
  "src/adapters/openfilm/cache-process-supervisor.ts",
  "src/adapters/openfilm/cache-process-custodian.py",
  "src/host/render/media-process-policy.mjs",
  "src/host/render/openfilm-offline-hooks.mjs",
  "src/host/render/openfilm-offline-wrapper.mjs",
  "src/host/render/openfilm-guard-rules.mjs",
]);

/**
 * The interpreter the custodian runs under.
 *
 * It is an absolute path, and it is NOT looked up in the PATH of the user: the
 * custodian is a part of the settlement, and another interpreter would be another
 * runtime. Its digest is part of the record, because the bytes of the custodian
 * only mean something under the interpreter they were reviewed with.
 */
const PYTHON_EXECUTABLE = "/usr/bin/python3.12";
/** The version of that interpreter, as it was recorded when it was reviewed. */
const PYTHON_VERSION = "3.12.3";

/**
 * The pinned upstream modules this draw loads.
 *
 * These are the modules the worker loads BY NAME: the producer that draws the
 * picture, the module the offline guard stands in front of, and the modules of the
 * pinned upstream that the Host already verifies before it loads anything of them.
 * Their digests come from the canonical lock and are never regenerated here.
 */
const PINNED_UPSTREAM_FILES = Object.freeze([
  "packages/openfilm/studio/server/pageframes.mjs",
  "packages/openfilm/src/host.mjs",
  "packages/openfilm/studio/server/film.mjs",
  "packages/openfilm/studio/server/ops.mjs",
  "packages/openfilm/studio/server/atomic.mjs",
  "packages/openfilm/src/film-doc.mjs",
]);

/** The kind of the manifest. A manifest of another kind is not read. */
const MANIFEST_KIND = "narralens.openfilm_cache_worker_integrity@1.0";

/** The digest of the bytes of a buffer. */
const sha256Of = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** The digest of a file of this repository, or null when it is not there. */
async function digestOf(relative) {
  try {
    return sha256Of(await readFile(resolve(REPOSITORY_ROOT, relative)));
  } catch {
    return null;
  }
}

/** The digest of a file by its absolute path, or null when it is not there. */
async function digestOfAbsolute(path) {
  try {
    return sha256Of(await readFile(path));
  } catch {
    return null;
  }
}

/**
 * The pinned upstream digests, as the canonical lock records them.
 *
 * They are COPIED from the lock. A digest that the lock does not carry is a failure
 * of the lock, not something this tool may invent.
 */
async function pinnedUpstreamDigests() {
  const lock = JSON.parse(await readFile(resolve(REPOSITORY_ROOT, UPSTREAM_LOCK_PATH), "utf8"));
  const known = { ...(lock.loaded_module_sha256 ?? {}), ...(lock.studio_loaded_module_sha256 ?? {}) };
  const digests = {};
  for (const relative of PINNED_UPSTREAM_FILES) {
    const digest = known[relative];
    if (typeof digest !== "string" || !/^[a-f0-9]{64}$/u.test(digest)) {
      throw new Error(`the canonical upstream lock does not pin ${relative}`);
    }
    digests[relative] = digest;
  }
  return digests;
}

/** The manifest as it is on disk, or null when there is none. */
async function readManifest() {
  try {
    return JSON.parse(await readFile(resolve(REPOSITORY_ROOT, MANIFEST_PATH), "utf8"));
  } catch {
    return null;
  }
}

/** Check the manifest against the bytes of this repository and against the lock. */
async function check() {
  const manifest = await readManifest();
  const problems = [];
  if (manifest === null) {
    problems.push(`${MANIFEST_PATH} is missing`);
  } else {
    if (manifest.kind !== MANIFEST_KIND) problems.push("the manifest is not of the known kind");
    const host = manifest.host_modules;
    if (host === null || typeof host !== "object") {
      problems.push("the manifest names no host module");
    } else {
      for (const relative of Object.keys(host)) {
        if (relative === MANIFEST_PATH) problems.push("the manifest names itself");
        if (!HOST_MODULES.includes(relative)) problems.push(`the manifest names an unknown module ${relative}`);
      }
      for (const relative of HOST_MODULES) {
        const expected = host[relative];
        if (typeof expected !== "string") {
          problems.push(`the manifest does not cover ${relative}`);
          continue;
        }
        const actual = await digestOf(relative);
        if (actual === null) problems.push(`${relative} is missing`);
        else if (actual !== expected) problems.push(`${relative} does not match the manifest`);
      }
    }
    const runtime = manifest.fixed_runtime;
    if (runtime === null || typeof runtime !== "object") {
      problems.push("the manifest names no fixed runtime");
    } else {
      const python = runtime.python;
      if (python === null || typeof python !== "object") {
        problems.push("the manifest names no interpreter");
      } else {
        if (python.executable !== PYTHON_EXECUTABLE) {
          problems.push("the manifest names another interpreter");
        }
        const actual = await digestOfAbsolute(String(python.executable));
        if (actual === null) problems.push("the interpreter is not there");
        else if (actual !== python.sha256) problems.push("the interpreter is not the reviewed one");
      }
      if (runtime.node_exec_path !== process.execPath) {
        problems.push("the manifest names another node executable");
      }
    }
    const pinned = manifest.pinned_upstream;
    let expectedPinned = null;
    try {
      expectedPinned = await pinnedUpstreamDigests();
    } catch (error) {
      problems.push(String(error?.message ?? error));
    }
    if (expectedPinned !== null) {
      if (pinned === null || typeof pinned !== "object") {
        problems.push("the manifest names no pinned upstream module");
      } else {
        for (const [relative, digest] of Object.entries(expectedPinned)) {
          if (pinned[relative] !== digest) {
            problems.push(`the pinned upstream digest of ${relative} is not the one of the canonical lock`);
          }
        }
        for (const relative of Object.keys(pinned)) {
          if (expectedPinned[relative] === undefined) {
            problems.push(`the manifest pins an upstream module the canonical lock does not name: ${relative}`);
          }
        }
      }
    }
  }
  return problems;
}

/** Write the manifest. Only `--generate` reaches this. */
async function generate() {
  const hostModules = {};
  for (const relative of HOST_MODULES) {
    const digest = await digestOf(relative);
    if (digest === null) throw new Error(`${relative} is missing: the manifest cannot be generated`);
    hostModules[relative] = digest;
  }
  const manifest = {
    kind: MANIFEST_KIND,
    host_modules: Object.fromEntries(Object.entries(hostModules).sort(([left], [right]) => left.localeCompare(right))),
    pinned_upstream: Object.fromEntries(
      Object.entries(await pinnedUpstreamDigests()).sort(([left], [right]) => left.localeCompare(right)),
    ),
    pinned_upstream_source: UPSTREAM_LOCK_PATH,
    fixed_runtime: {
      node_exec_path: process.execPath,
      python: {
        executable: PYTHON_EXECUTABLE,
        sha256: await digestOfAbsolute(PYTHON_EXECUTABLE),
        version: PYTHON_VERSION,
      },
    },
    generated_by: "tools/openfilm-cache-worker-integrity.mjs",
  };
  // The manifest does not hash itself: it is not in the list of the host modules.
  if (Object.prototype.hasOwnProperty.call(manifest.host_modules, MANIFEST_PATH)) {
    throw new Error("the manifest names itself");
  }
  const text = `${JSON.stringify(manifest, null, 2)}\n`;
  await writeFile(resolve(REPOSITORY_ROOT, MANIFEST_PATH), text, "utf8");
  return { path: MANIFEST_PATH, sha256: sha256Of(Buffer.from(text, "utf8")) };
}

const args = process.argv.slice(2);
const unknown = args.filter((argument) => argument !== "--check" && argument !== "--generate");
if (unknown.length > 0) {
  process.stdout.write(`${JSON.stringify({ ok: false, reason: `unknown argument: ${unknown[0]}` })}\n`);
  process.exit(2);
}
const wantsGenerate = args.includes("--generate");
const wantsCheck = args.includes("--check") || !wantsGenerate;

if (wantsGenerate) {
  try {
    const written = await generate();
    process.stdout.write(`${JSON.stringify({ ok: true, generated: written })}\n`);
  } catch (error) {
    process.stdout.write(`${JSON.stringify({ ok: false, reason: String(error?.message ?? error) })}\n`);
    process.exit(1);
  }
}

if (wantsCheck) {
  const problems = await check();
  if (problems.length > 0) {
    process.stdout.write(`${JSON.stringify({ ok: false, problems }, null, 2)}\n`);
    process.exit(1);
  }
  process.stdout.write(`${JSON.stringify({ ok: true, checked: HOST_MODULES.length })}\n`);
}
